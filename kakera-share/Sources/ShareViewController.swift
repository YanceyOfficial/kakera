import UIKit
import SwiftUI

/// The share extension's entry point ("Add to Kakera" in any app's share sheet): hosts
/// `ShareView`, which reads the shared text or picture and offers its words.
final class ShareViewController: UIViewController {
    override func viewDidLoad() {
        super.viewDidLoad()
        let host = UIHostingController(rootView: ShareView(context: extensionContext))
        addChild(host)
        host.view.frame = view.bounds
        host.view.autoresizingMask = [.flexibleWidth, .flexibleHeight]
        view.addSubview(host.view)
        host.didMove(toParent: self)
    }
}
